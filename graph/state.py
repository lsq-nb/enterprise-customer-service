"""
LangGraph 状态定义
定义多智能体工作流的共享状态
"""
from __future__ import annotations

import logging
from typing import Annotated, Any

from langgraph.graph import add_messages
from langchain_core.messages import AIMessage, HumanMessage

logger = logging.getLogger(__name__)


class AgentState:
    """
    多智能体协作工作流状态

    状态机节点：
    ┌─────────────────────────────────────────────────────────────┐
    │                      [入口] START                            │
    │                           ↓                                 │
    │              ┌────────────▼────────────┐                    │
    │              │     route (意图路由)     │                    │
    │              └────────────┬────────────┘                    │
    │                           ↓                                 │
    │        ┌──────────┬───────┴───────┬──────────┐             │
    │        ↓          ↓               ↓           ↓             │
    │   retrieve    retrieve      execute_tools   chitchat        │
    │   (RAG检索)   (RAG检索)       (工具执行)    (闲聊处理)       │
    │        │          │               │           │             │
    │        └──────────┴───────┬───────┘           │             │
    │                           ↓                    │             │
    │              ┌────────────▼────────────┐       │             │
    │              │  generate_answer        │───────┘             │
    │              │   (答案生成)            │                     │
    │              └────────────┬────────────┘                     │
    │                           ↓                                 │
    │              ┌────────────▼────────────┐                    │
    │              │  verify_answer          │                    │
    │              │   (答案验证)            │                    │
    │              └────────────┬────────────┘                    │
    │                           ↓                                 │
    │              ┌────────────▼────────────┐                    │
    │              │  should_continue?       │                    │
    │              │  (是否需要继续处理)      │                    │
    │              └────────────┬────────────┘                    │
    │                           ↓ yes                             │
    │              ┌────────────▼────────────┐                    │
    │              │     finalize (输出)      │                    │
    │              └────────────┬────────────┘                    │
    │                           ↓                                 │
    │                      [出口] END                              │
    └─────────────────────────────────────────────────────────────┘
    """

    # ────────────────────────────────────────────
    # 消息列表（支持多轮对话）
    # ────────────────────────────────────────────
    messages: list[Any] = []

    # ────────────────────────────────────────────
    # 意图识别结果
    # ────────────────────────────────────────────
    intent: str = "general_qa"
    """用户意图标签"""
    intent_confidence: float = 0.0
    """意图识别置信度"""
    intent_reasoning: str = ""
    """意图识别推理过程"""

    # ────────────────────────────────────────────
    # RAG 检索结果
    # ────────────────────────────────────────────
    retrieved_docs: list[Any] = []
    """检索到的相关文档列表"""
    retrieval_source: str = ""
    """检索来源说明"""

    # ────────────────────────────────────────────
    # 工具调用结果
    # ────────────────────────────────────────────
    tool_calls: list[dict[str, Any]] = []
    """已执行的工具调用记录"""
    tool_call_count: int = 0
    """工具调用次数"""
    max_tool_calls: int = 3
    """最大工具调用次数限制"""

    # ────────────────────────────────────────────
    # 回答生成结果
    # ────────────────────────────────────────────
    answer: str = ""
    """最终生成的回答"""
    answer_sources: list[str] = []
    """回答引用的来源"""
    answer_confidence: float = 0.0
    """回答置信度"""

    # ────────────────────────────────────────────
    # 流程控制
    # ────────────────────────────────────────────
    need_tool: bool = False
    """是否需要调用工具"""
    need_escalation: bool = False
    """是否需要人工转接"""
    step: str = "start"
    """当前步骤标识"""
    error: str | None = None
    """错误信息"""

    # ────────────────────────────────────────────
    # 对话元数据
    # ────────────────────────────────────────────
    conversation_id: str = ""
    """会话ID，用于多轮对话关联"""
    user_id: str = ""
    """用户ID"""
    created_at: str = ""
    """创建时间"""
